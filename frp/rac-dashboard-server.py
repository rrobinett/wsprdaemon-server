def save_login(rac, which, user):
    """Set (or with user '' clear) the saved login for one RAC's VM or host."""
    with _LOGINS_LOCK:
        d = load_logins()
        ent = d.get(str(rac)) or {}
        if user:
            ent[which] = user
        else:
            ent.pop(which, None)
        if ent:
            d[str(rac)] = ent
        else:
            d.pop(str(rac), None)
        tmp = LOGINS_FILE + '.tmp'
        with open(tmp, 'w') as fh:
            json.dump(d, fh, indent=1, sort_keys=True)
            fh.write('\n')
        os.replace(tmp, LOGINS_FILE)


