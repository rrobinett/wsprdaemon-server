                # channel can honestly offer over a shared VPN.  Never widen
                # this to StrictHostKeyChecking=no or a /dev/null known_hosts:
                # those silently accept a changed key forever, on every host,
                # including the ones whose identity really is stable.
                #
                # ssh-keygen -R takes the [host]:port form for a non-22 port,
                # and removes every key type for that endpoint -- which matters
                # because the stale entry is often ECDSA while the station now
                # offers ED25519.
