# --------------------------------------------------------------------------- DB
def db():
    con = sqlite3.connect(DB_PATH, timeout=5)
    con.execute('PRAGMA journal_mode=WAL')
    return con


def init_db():
    con = db()
    con.execute('''CREATE TABLE IF NOT EXISTS sessions(
        id INTEGER PRIMARY KEY,
        name TEXT NOT NULL,
        connected_at INTEGER NOT NULL,
        last_seen INTEGER NOT NULL,
        disconnected_at INTEGER)''')
    con.execute('CREATE INDEX IF NOT EXISTS idx_sess_name ON sessions(name)')
    try:  # added later: remember each station's RAC number so OFFLINE
        con.execute('ALTER TABLE sessions ADD COLUMN rac INTEGER')
    except sqlite3.OperationalError:
        pass  # column already exists
    con.commit()
    con.close()


def record(online, now):
    """online: {client_name: rac_or_None}"""
    con = db()
    c = con.cursor()
    for name, rac in online.items():
        row = c.execute('SELECT id FROM sessions WHERE name=? AND disconnected_at IS NULL',
                        (name,)).fetchone()
        if row:
            c.execute('UPDATE sessions SET last_seen=?, rac=COALESCE(?,rac) WHERE id=?',
                      (now, rac, row[0]))
        else:
            c.execute('INSERT INTO sessions(name,connected_at,last_seen,rac) VALUES(?,?,?,?)',
                      (name, now, now, rac))
    for sid, name, last_seen in c.execute(
            'SELECT id,name,last_seen FROM sessions WHERE disconnected_at IS NULL').fetchall():
        if name not in online:
            c.execute('UPDATE sessions SET disconnected_at=? WHERE id=?', (last_seen, sid))
    c.execute('DELETE FROM sessions WHERE disconnected_at IS NOT NULL AND disconnected_at<?',
              (now - RETAIN_SEC,))
    con.commit()
    con.close()


def migrated_legacy(names, rac_for):
    """The ' [legacy]' rows that a non-legacy row supersedes: same base name,
    or same RAC number. A station upgraded from the open tier to the secure
    tier keeps its open-tier history (GET /?h=NAME) but is listed once, as the
    live secure entry, instead of once active and once 'legacy, offline'."""
    plain = {n for n in names if not n.endswith(' [legacy]')}
    racs = {rac_for(n) for n in plain} - {None}
    hidden = set()
    for n in names:
        if not n.endswith(' [legacy]'):
            continue
        base = n[:-len(' [legacy]')]
        if base in plain or rac_for(n) in racs:
            hidden.add(n)
    return hidden


def status_map():
    con = db()
    rows = con.execute('''SELECT name,
        MAX(disconnected_at IS NULL) AS active,
        MAX(last_seen) AS last_seen,
        MIN(connected_at) AS first_seen,
        COUNT(*) AS sessions,
        MAX(rac) AS rac
        FROM sessions GROUP BY name''').fetchall()
    con.close()
    return {r[0]: {'active': bool(r[1]), 'last_seen': r[2],
                   'first_seen': r[3], 'sessions': r[4], 'rac': r[5]} for r in rows}


def history(name):
    con = db()
    rows = con.execute('''SELECT connected_at,disconnected_at,last_seen FROM sessions
        WHERE name=? ORDER BY connected_at DESC LIMIT 500''', (name,)).fetchall()
    con.close()
    return rows


# ----------------------------------------------------------------------- poller
def fetch_proxies():
    out = []
    for src, url, auth in FRPS_APIS:
        try:
            req = urllib.request.Request(url)
            req.add_header('Authorization',
                           'Basic ' + base64.b64encode(auth.encode()).decode())
            with urllib.request.urlopen(req, timeout=8) as r:
                for p in json.load(r).get('proxies') or []:
                    p['_src'] = src
                    out.append(p)
        except Exception:
            pass  # one instance being down must not blank the whole page
    return out


def strip_hash(name):
    if '.' in name:
        head, rest = name.split('.', 1)
        if len(head) == 16 and all(c in '0123456789abcdef' for c in head):
            return rest
    return name


def parse(name):
    for suf, kind, proto, tier, label in SUFFIXES:
        if name.endswith(suf):
            return name[:-len(suf)], kind, proto, tier, label
    if name.endswith('-WEB'):
        client = name[:-4]
        if 'PROXMOX' in client.upper():
            return client, 'web', 'https', 'mesh-only', 'Proxmox UI'
        return client, 'web', 'http', 'shareable', 'ka9q-web'
    return name, 'ssh', 'ssh', 'mesh-only', 'SSH'


def rac_of(svcs):
    """Derive the RAC number from any of a client's ports — every band
    (35800 ssh/vm-ssh, 45800 web/vm-web, 50800 host-ssh, 55800 host-ui)
    is base + rac."""
    for s in svcs.values():
        p = s.get('port')
        if isinstance(p, int):
            if 37800 <= p <= 37899:      # Wsprsonde band: ID 2000-2099
                return p - 35800
            for base in (35800, 40800, 45800, 50800, 55800):
                if base <= p <= base + 999:
                    return p - base
    return None


def is_sonde(rac):
    return rac is not None and 2000 <= rac <= 2099


def load_creds():
    """Admin-supplied per-RAC credentials map, re-read each request so the
    admin can refresh it without restarting. {} if absent/unreadable."""
    try:
        with open(CREDS_FILE) as fh:
            return json.load(fh)
    except Exception:
        return {}


def account_and_ssh_port(svcs, rac):
    """Login account + primary SSH port for a station, for tooling (ssr.sh).

    account:  an explicit frps-metadata user on any of the station's SSH
              services if present, else this gateway's DEFAULT_ACCOUNT.
    ssh_port: the receiver/VM SSH port (the 35800+rac band) when live, else
              the deterministic 35800+rac. Reaching it still requires the
              admin WireGuard tier plus a valid SSH key — the port formula
              itself is not a secret."""
    account = None
    ssh_port = None
    for s in svcs.values():
        if s.get('kind') != 'ssh':
            continue
        if account is None and s.get('user'):
            account = s['user']       # reported by the frpc client (metadatas.user)
        p = s.get('port')
        if ssh_port is None and isinstance(p, int) and (
                35800 <= p <= 36799 or 37800 <= p <= 37899):
            ssh_port = p
    if ssh_port is None and rac is not None:
        ssh_port = 35800 + rac
    ### from_meta: True when the station itself reported its login account, so
    ### callers can let it win over the admin's rac-creds table.
    from_meta = account is not None
    return (account or DEFAULT_ACCOUNT), ssh_port, from_meta


def live_services():
    """{client: {label: svc}} for currently-online proxies, + {client: rac}."""
    clients = {}
    for p in fetch_proxies():
        name = strip_hash(p.get('name', ''))
        if not name or p.get('status') != 'online':
            continue
        client, kind, proto, tier, label = parse(name)
        if p.get('_src') == 'legacy':
            client += ' [legacy]'
        conf = p.get('conf') or {}
        # frp v0.64 (gw2) uses camelCase remotePort/metadatas; older frp
        # v0.3x (HamSCI) uses snake_case remote_port/meta_datas — accept both.
        port = conf.get('remotePort')
        if port is None:
            port = conf.get('remote_port')
        meta = conf.get('metadatas') or conf.get('meta_datas') or {}
        clients.setdefault(client, {})[label] = {
            'kind': kind, 'proto': proto, 'tier': tier, 'label': label,
            'port': port,
            'user': meta.get('user') if isinstance(meta, dict) else None}
    online = {c: rac_of(svcs) for c, svcs in clients.items()}
    return clients, online


def poller():
    while True:
        try:
            _clients, online = live_services()
            record(online, int(time.time()))
        except Exception:
            pass
        time.sleep(POLL_SEC)


# ------------------------------------------------------------------ formatting
def ago(ts, now):
    d = max(0, now - ts)
    if d < 60:
        return f'{d}s ago'
    if d < 3600:
        return f'{d // 60}m ago'
    if d < 86400:
        return f'{d // 3600}h ago'
    return f'{d // 86400}d ago'


def utc(ts):
    return time.strftime('%Y-%m-%d %H:%M', time.gmtime(ts)) + 'Z'


def dur(a, b):
    s = max(0, b - a)
    if s < 3600:
        return f'{s // 60}m'
    if s < 86400:
        return f'{s // 3600}h {s % 3600 // 60}m'
    return f'{s // 86400}d {s % 86400 // 3600}h'


