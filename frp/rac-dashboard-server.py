def render_main(gw_ip, tier, sort='name', desc=False, only_sonde=False):
    now = int(time.time())
    clients, _online = live_services()
    stat = status_map()
    creds = load_creds() if tier == 'mesh' else {}   # passwords: mesh tier only
    # tier-filter live services
    vis = {}
    for name, svcs in clients.items():
        f = {lab: s for lab, s in svcs.items() if svc_visible(s, tier)}
        if f:
            vis[name] = f
    # Sonde-only station filter: forced for the wd-sonde tier (which must not
    # even see the names of non-sonde stations), optional for admin tiers via
    # GET /sondes.
    if tier == 'sonde' or only_sonde:
        only_sonde = True
        vis = {n: svcs for n, svcs in vis.items()
               if is_sonde(rac_of(svcs)) or is_sonde(stat.get(n, {}).get('rac'))}
        stat = {n: st for n, st in stat.items() if is_sonde(st.get('rac'))}
    present = [(h, ls, k) for (h, ls, k) in COLUMNS
               if any(any(l in vis[c] for l in ls) for c in vis)]

    def row_facts(name):
        rac = rac_of(vis.get(name, {})) if name in vis else None
        if rac is None:
            rac = stat.get(name, {}).get('rac')
        active = bool(stat.get(name, {}).get('active') or name in vis)
        ls = stat.get(name, {}).get('last_seen') or 0
        return rac, active, ls

    def sort_key(name):
        rac, active, ls = row_facts(name)
        if sort == 'rac':
            return (rac is None, rac if rac is not None else 0, name.lower())
        if sort == 'status':
            # active first, then most recently seen
            return (not active, -ls, name.lower())
        return (name.lower(),)
    names = sorted(set(stat) | set(vis), key=sort_key, reverse=desc)
    hidden = migrated_legacy(names, lambda n: row_facts(n)[0])
    names = [n for n in names if n not in hidden]

    heading = ' Wsprsonde status' if only_sonde else ' Remote Access Channel (RAC)'
    b = ['<h1>' + html.escape(TITLE) + heading + '</h1>']
    tl = {'mesh': 'full mesh view', 'sonde': 'wd-sonde view (Wsprsonde hosts only)'}.get(
        tier, 'wd-rac view (shareable services only)')
    # Admin tiers get a link between the full view and the sonde-only view;
    # the wd-sonde tier has nothing else to link to.
    nav = ''
    if tier != 'sonde':
        nav = (' &middot; <a href="/">all stations</a>' if only_sonde
               else ' &middot; <a href="/sondes">Wsprsondes only</a>')
    # Address used in the service links: the sonde-only admin view shows the
    # address typical sonde users have (see SONDE_USER_GW); everything else
    # uses the viewer's own arrival address.
    link_ip = SONDE_USER_GW if (only_sonde and tier != 'sonde') else gw_ip
    # Admin tiers carry a note that the probe script updates once it learns
    # which VPN this browser actually has (see PROBE_SCRIPT).
    ipnote = ('' if tier == 'sonde' else
              f' &middot; <span id="gwnote">ssh links use <code>{link_ip}</code></span>')
    nact = sum(1 for n in names if stat.get(n, {}).get('active') or n in vis)
    b.append(f'<div class="sub">via gw2 <code>{gw_ip}</code> &middot; {tl} &middot; '
             f'{nact} active / {len(names)} known{nav}{ipnote} &middot; auto-refresh 30s</div>')
    def th(col, label):
        # clicking the current sort column flips direction
        d = '&amp;d=1' if (sort == col and not desc) else ''
        arrow = (' &#9660;' if desc else ' &#9650;') if sort == col else ''
        return f'<th><a href="?s={col}{d}">{label}</a>{arrow}</th>'
    b.append('<table><tr>' + th('name', 'Name') + th('rac', 'RAC') + th('status', 'Status'))
    if tier == 'mesh':
        b.append('<th>Login</th>')
    for h, _ls, _k in present:
        b.append(f'<th class="svc">{h}</th>')
    b.append('</tr>')
    for name in names:
        rac, active, _lastseen = row_facts(name)
        ls = stat.get(name, {}).get('last_seen')
        rowcls = '' if active else ' class="off-row"'
        st = '<span class="on">&#9679; active</span>' if active else (
            f'<span class="ago">last seen {ago(ls, now)}</span>' if ls else '&mdash;')
        b.append(f'<tr{rowcls}><td class="name">'
                 f'<a href="?h={html.escape(name)}">{html.escape(name)}</a></td>'
                 f'<td class="name">{rac if rac is not None else "&mdash;"}</td>'
                 f'<td>{st}</td>')
        if tier == 'mesh':
            ### Login: real account + a click-to-copy password (password passed
            ### via a data- attribute, never inlined into the JS string).
            c = creds.get(str(rac)) if rac is not None else None
            acct = (c or {}).get('account') or ''
            pw = (c or {}).get('password') or ''
            if pw:
                cell = ('%s / <a class="act" href="#" data-pw="%s" '
                        'onclick="cp(this,this.dataset.pw);return false" '
                        'title="copy password">pw</a>'
                        % (html.escape(acct) or '&mdash;', html.escape(pw)))
            elif acct:
                cell = html.escape(acct)
            else:
                cell = '<span class="dot">&middot;</span>'
            b.append(f'<td>{cell}</td>')
        svcs = vis.get(name, {})
        for _h, labels, kind in present:
            svc = next((svcs[l] for l in labels if l in svcs), None)
            if not svc:
                b.append('<td class="svc"><span class="dot">&middot;</span></td>')
            elif kind == 'web':
                b.append('<td class="svc"><a class="act web" target="_blank" '
                         'data-proto="%s" data-port="%s" href="%s://%s:%s/">open</a></td>'
                         % (svc['proto'], svc['port'], svc['proto'], link_ip, svc['port']))
            else:
                default_user = 'wsprsonde' if svc['tier'] == 'sonde' else 'root'
                user = svc.get('user') or default_user
                cmd = 'ssh -p %s %s@%s' % (svc['port'], user, link_ip)
                b.append('<td class="svc"><a class="act ssh" href="#" title="%s" '
                         'data-port="%s" data-user="%s" '
                         'onclick="cp(this,sshcmd(this));return false">ssh</a></td>'
                         % (cmd, svc['port'], user))
        b.append('</tr>')
    b.append('</table>')
    # window.GW is what sshcmd()/cp() compose the command from; the probe
    # (admin tiers only) may then update it to the viewer's own VPN.
    b.insert(0, '<script>window.GW=%s</script>' % json.dumps(link_ip))
    if tier != 'sonde':
        b.append(PROBE_SCRIPT.replace('%CANDS%', json.dumps([list(c) for c in GW_CANDIDATES]))
                             .replace('%PORT%', str(PORT)))
    return page(TITLE + (' Wsprsondes' if only_sonde else ' RAC'), ''.join(b))


def render_api(tier):
    """Machine-readable view for tooling (ssr.sh etc.): every known station
    with its RAC number, live services (tier-filtered like the page), and
    status. GET /api"""
    now = int(time.time())
    clients, _online = live_services()
    stat = status_map()
    creds = load_creds()
    out = []

    def rac_for(name):
        r = rac_of(clients.get(name, {})) if name in clients else None
        return r if r is not None else stat.get(name, {}).get('rac')

    names = sorted(set(stat) | set(clients))
    hidden = migrated_legacy(names, rac_for)
    for name in names:
        if name in hidden:
            continue
        svcs = {lab: s for lab, s in clients.get(name, {}).items()
                if svc_visible(s, tier)}
        rac = rac_for(name)
        if tier == 'sonde' and not is_sonde(rac):
            continue
        account, ssh_port, from_meta = account_and_ssh_port(clients.get(name, {}), rac)
        ### Account precedence: what the frpc client itself reported
        ### (metadatas.user) wins; otherwise the admin's rac-creds table; else
        ### the gateway default. The table also supplies password + port_fwd
        ### (mesh tier only) regardless of where the account came from.
        c = creds.get(str(rac)) if rac is not None else None
        if not from_meta and c and c.get('account'):
            account = c['account']
        station = {
            'name': name,
            'rac': rac,
            'account': account,
            'ssh_port': ssh_port,
            'legacy': name.endswith(' [legacy]'),
            'active': bool(stat.get(name, {}).get('active') or name in clients),
            'last_seen': stat.get(name, {}).get('last_seen'),
            'services': {lab: {'port': s['port'], 'proto': s['proto'],
                               'kind': s['kind'], 'tier': s['tier']}
                         for lab, s in svcs.items()},
        }
        if c and tier == 'mesh':
            if c.get('password'):
                station['password'] = c['password']
            if c.get('port_fwd'):
                station['port_fwd'] = c['port_fwd']
        out.append(station)
    return json.dumps({'generated': now, 'tier': tier, 'gateway': GATEWAY,
                       'default_account': DEFAULT_ACCOUNT, 'stations': out},
                      indent=1) + '\n'


def render_history(name, gw_ip):
    now = int(time.time())
    rows = history(name)
    b = [f'<h1>{html.escape(name)} &mdash; connection history</h1>',
         '<div class="sub"><a href="/">&larr; all machines</a> &middot; '
         f'{len(rows)} session(s) &middot; via gw2 <code>{gw_ip}</code></div>']
    if not rows:
        b.append('<p>No history recorded yet.</p>')
        return page(name + ' history', ''.join(b))
    b.append('<table><tr><th>Connected</th><th>Disconnected</th><th>Duration</th></tr>')
    for connected_at, disconnected_at, last_seen in rows:
        if disconnected_at is None:
            end = '<span class="on">&#9679; active</span>'
            d = dur(connected_at, now)
        else:
            end = f'{utc(disconnected_at)} <span class="ago">({ago(disconnected_at, now)})</span>'
            d = dur(connected_at, disconnected_at)
        b.append(f'<tr><td>{utc(connected_at)}</td><td>{end}</td><td>{d}</td></tr>')
    b.append('</table>')
    return page(name + ' history', ''.join(b))


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        local = self.connection.getsockname()[0]
        tier = ADMIN_NETS.get(local)
        if tier is None:
            self.send_response(403)
            self.end_headers()
            self.wfile.write(b'forbidden: WireGuard admin networks only')
            return
        try:
            u = urlparse(self.path)
            q = parse_qs(u.query)
            ctype = 'text/html; charset=utf-8'
            if u.path == '/ping':
                # reachability probe for the client-side VPN detection; CORS
                # header lets a page served from one gateway address probe
                # the others (all still gated by ADMIN_NETS above).
                self.send_response(204)
                self.send_header('Access-Control-Allow-Origin', '*')
                self.send_header('Cache-Control', 'no-store')
                self.end_headers()
                return
            if u.path == '/conf':
                # encrypted credential blobs: full-trust mesh tier only
                if tier != 'mesh':
                    self.send_response(403)
                    self.end_headers()
                    self.wfile.write(b'forbidden: mesh tier only')
                    return
                f = (q.get('f') or ['rac-master.conf.enc'])[0]
                if f not in CONF_WHITELIST:
                    self.send_response(404)
                    self.end_headers()
                    self.wfile.write(b'unknown conf')
                    return
                try:
                    with open(os.path.join(CONF_DIR, f), 'rb') as fh:
                        blob = fh.read()
                except OSError:
                    self.send_response(404)
                    self.end_headers()
                    self.wfile.write(b'conf not present on gateway')
                    return
                self.send_response(200)
                self.send_header('Content-Type', 'application/octet-stream')
                self.send_header('Content-Length', str(len(blob)))
                self.end_headers()
                self.wfile.write(blob)
                return
            if u.path == '/api':
                body = render_api(tier)
                ctype = 'application/json'
            elif 'h' in q and q['h']:
                # sonde tier: history only for stations in the sonde band
                if tier == 'sonde' and not is_sonde(
                        status_map().get(q['h'][0], {}).get('rac')):
                    self.send_response(404)
                    self.end_headers()
                    self.wfile.write(b'unknown station')
                    return
                body = render_history(q['h'][0], local)
            else:
                sort = (q.get('s') or ['name'])[0]
                if sort not in ('name', 'rac', 'status'):
                    sort = 'name'
                body = render_main(local, tier, sort, bool(q.get('d')),
                                   only_sonde=(u.path == '/sondes'))
            page_b = body.encode()
        except Exception as exc:
            self.send_response(502)
            self.end_headers()
            self.wfile.write(('error: %s' % exc).encode())
            return
        self.send_response(200)
        self.send_header('Content-Type', ctype)
        self.send_header('Content-Length', str(len(page_b)))
        self.end_headers()
        self.wfile.write(page_b)

    def log_message(self, *a):
        pass


