#!/usr/bin/env python3
"""Render the system-log TTL drop-in from the repo template.

usage: render-system-log-ttl.py TEMPLATE TABLES_FILE > drop-in.xml

TABLES_FILE has one existing/enabled system table name per line.  Only
template elements whose tag is in that list are emitted: a <foo_log> section
in config.d enables that log even when the server has it disabled, so the
installed drop-in must never name a log the server is not running.
The template remains the single source of <ttl> values.
"""
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

template, tables_file = sys.argv[1], sys.argv[2]
with open(tables_file) as f:
    present = {line.strip() for line in f if line.strip()}

out = []
for el in ET.parse(template).getroot():
    ttl = el.find("ttl")
    if ttl is None or not (ttl.text or "").strip() or el.tag not in present:
        continue
    out.append(f"    <{el.tag}>\n        <ttl>{escape(ttl.text.strip())}</ttl>\n    </{el.tag}>")

print("<!-- Generated by install-servers.sh from clickhouse-config/wd-system-log-ttl.xml;")
print("     only log tables enabled on this server at install time. Do not edit. -->")
print("<clickhouse>")
print("\n".join(out))
print("</clickhouse>")
